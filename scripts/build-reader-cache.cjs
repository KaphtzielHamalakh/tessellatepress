// Re-run after changing any reader asset. No packages or production build needed.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.join(__dirname, '../freecomicreader');
const excluded = new Set(['sw.js', 'asset-manifest.json', 'SETUP.md']);
function walk(dir) { return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)]); }
const assets = walk(root).filter(file => !excluded.has(path.basename(file))).map(file => path.relative(root, file).replaceAll('\\', '/')).sort();
const hash = crypto.createHash('sha256');
for (const asset of assets) hash.update(asset).update(fs.readFileSync(path.join(root, asset)));
const version = hash.digest('hex').slice(0, 16);
fs.writeFileSync(path.join(root, 'asset-manifest.json'), JSON.stringify(assets, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'sw.js'), `// Generated by scripts/build-reader-cache.cjs. Cache version follows asset contents.
const CACHE = 'fcr-${version}';
const BASE = new URL('./', self.location.href);
const ASSETS = ${JSON.stringify(assets)};
const URLS = new Set(ASSETS.map(path => new URL(path, BASE).href));
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  try { await cache.addAll([...URLS]); } catch (error) { await caches.delete(CACHE); throw error; }
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const key of await caches.keys()) if (key.startsWith('fcr-') && key !== CACHE) await caches.delete(key);
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== BASE.origin || !url.pathname.startsWith(BASE.pathname)) return;
  const key = url.pathname === BASE.pathname ? new URL('index.html', BASE).href : url.origin + url.pathname;
  if (!URLS.has(key)) return;
  event.respondWith(caches.open(CACHE).then(async cache => (await cache.match(key)) || fetch(event.request)));
});
`);
console.log(`Offline cache ${version}: ${assets.length} assets`);
